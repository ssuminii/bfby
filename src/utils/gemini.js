import { GoogleGenAI } from '@google/genai'

const ai = new GoogleGenAI({
  apiKey: import.meta.env.VITE_GEMINI_API_KEY,
})

const AXES = ['이미 있나', '얼마나 쓸까', '왜 하필 지금', '예산이 감당되는가']

const CATEGORIES = ['의류', '뷰티', '전자기기', '생활용품', '식품', '취미·운동']

const generate = async (prompt) => {
  const response = await ai.models.generateContent({
    model: 'gemini-3.5-flash-lite',
    contents: prompt,
    config: {
      responseMimeType: 'application/json',
    },
  })

  if (!response.text) {
    throw new Error('Gemini 응답이 비어 있습니다.')
  }

  return JSON.parse(response.text)
}

export async function generateFirstQuestion(productInfo) {
  return generate(`
  상품명: ${productInfo.name}
  가격: ${productInfo.price?.toLocaleString()}원

  다음 작업을 수행해줘.

  1. 이 상품의 카테고리를 [${CATEGORIES.join(', ')}] 중 하나로 분류해줘.

  2. 첫 번째 질문을 만들어줘.

  [첫 번째 질문의 목적]

  - 질문 축은 "${AXES[0]}"이야.
  - 사용자가 이미 비슷한 용도나 역할의 제품을 가지고 있는지 확인하는 질문이야.
  - 단순히 같은 상품을 가지고 있는지가 아니라, 새로 구매할 필요성이 있는지를 판단하는 데 도움이 되는 질문을 만들어줘. // 추가: 단순 보유 여부가 아니라 구매 필요성까지 확인하도록 목적 구체화

  [질문 생성 원칙]

  - 상품명에서 확실하게 알 수 있는 정보가 있다면 질문에 자연스럽게 활용해.
  - 상품명에 없는 특징은 임의로 추측하지 마.
  - 질문은 한 문장으로 짧고 자연스럽게 작성해.
  - 실제 사람이 대화하듯 쉬운 표현을 사용해.
  - 지나치게 딱딱하거나 상담 문구 같은 표현은 피해야 해. 

  [선택지 생성 원칙]

  - 질문에 직접 답할 수 있는 선택지 4개를 만들어줘.
  - 각 선택지는 15자 이내로 작성해.
  - 선택지끼리 의미가 최대한 겹치지 않게 해.
  - 사용자의 상태를 임의로 가정하지 마.
  - 상품 정보에 없는 특징을 만들어내지 마.

  JSON 형식으로만 반환:
  {
    "category": "카테고리",
    "question": "질문 문장",
    "options": ["선택지1", "선택지2", "선택지3", "선택지4"]
  }
`)
}

export async function generateNextQuestion(productInfo, category, previousQAs, axisIndex) {
  const axis = AXES[axisIndex]

  if (!axis) {
    throw new Error('유효하지 않은 질문 축입니다.') // 잘못된 axisIndex로 프롬프트가 생성되는 상황 방지
  }

  const history = previousQAs
    .map((qa, i) => `Q${i + 1}(${AXES[i]}): ${qa.question} → 답변: ${qa.answer}`)
    .join('\n')

  return generate(`
  상품명: ${productInfo.name}
  가격: ${productInfo.price?.toLocaleString()}원
  카테고리: ${category}

  지금까지의 질문과 사용자 답변:
  ${history}

  이번 질문의 축: "${axis}"

  지금까지의 사용자 답변을 분석한 뒤 다음 질문을 만들어줘.

  [가장 중요한 원칙]

  이번 질문의 축은 반드시 "${axis}"으로 유지하되,
  질문의 구체적인 내용과 선택지는 지금까지의 사용자 답변에 따라 달라질 수 있어야 해. // 변경: 질문 축만 고정하고 실제 질문은 이전 답변에 따라 적응하도록 명확화

  단순히 이전 답변을 질문 문장에 끼워 넣는 것이 목적이 아니야.
  이전 답변을 통해 알게 된 사용자 상황을 바탕으로
  이번 축에서 "아직 확인하지 못한 것" 또는 "추가로 확인할 필요가 있는 것"을 질문해. // 추가: 이전 답변을 인용하는 대신 다음 질문의 방향을 결정하는 근거로 사용

  [이전 답변 분석 방법]

  지금까지의 모든 답변을 보고 다음 내용을 파악해.

  - 사용자가 이미 비슷한 제품을 가지고 있는지
  - 새 제품이 실제로 추가로 필요한 상황인지
  - 구매 후 실제로 얼마나 사용할 가능성이 있는지
  - 구매 필요성이 충분히 드러났는지
  - 순간적으로 사고 싶은 것에 가까운지
  - 이번 질문 축과 직접적으로 연결되는 정보가 있는지 // 추가: AI가 이전 답변을 먼저 해석하도록 분석 기준 제공

  이 분석 결과를 바탕으로 현재 사용자에게 가장 의미 있는 질문을 하나 만들어줘.

  [이전 답변 활용 원칙]

  - 이전 답변과 현재 질문 축이 직접적으로 관련 있다면 그 맥락을 활용해 질문을 구체화해.
  - 단순히 이전 답변을 그대로 반복하거나 문장 앞에 붙이지 마.
  - 이미 이전 질문에서 확인한 내용을 똑같이 다시 묻지 마.
  - 가장 최근 답변만 보지 말고 지금까지의 답변 전체를 참고해.
  - 이전 답변과 현재 축의 관련성이 낮다면 억지로 연결하지 마.
  - 관련성이 낮다면 현재 축에 맞는 자연스러운 질문을 독립적으로 만들어. // 변경: 억지 개인화보다 자연스러움을 우선하도록 설정

  예를 들어,
  "일주일에 두세 번 사용할 것 같다"는 답변과
  "왜 하필 지금"이라는 축을
  "일주일에 두세 번 사용하려면 왜 지금 사나요?"처럼
  인과관계가 있는 것처럼 억지로 연결하면 안 돼. 

  대신 이전 답변이 현재 축에서 새로운 판단 근거가 된다면
  그 의미를 활용해서 질문의 초점을 바꿔줘.

  [질문 축의 의미]

  "${AXES[0]}"
  - 이미 비슷한 역할을 하는 제품이 있는지 확인
  - 새 제품을 추가로 구매할 필요가 있는지 확인

  "${AXES[1]}"
  - 구매 후 실제 생활에서 사용할 상황이 충분한지 확인
  - 일시적인 관심이 아니라 실제 사용 가능성이 있는지 확인

  "${AXES[2]}"
  - 굳이 지금 구매해야 하는 이유나 계기가 있는지 확인
  - 필요에 의한 구매인지 단순한 순간적인 욕구인지 확인

  "${AXES[3]}"
  - 이 가격을 지불해도 현재 소비 상황에서 부담스럽지 않은지 확인
  - 구매 후 후회할 정도로 무리한 지출은 아닌지 확인 // 변경: 각 축 안에서도 여러 방향으로 질문할 수 있도록 목적을 넓게 정의

  [질문 작성 원칙]

  - 질문은 한 문장으로 작성해.
  - 실제 사람이 대화하듯 자연스럽고 쉽게 작성해.
  - 모든 질문은 존댓말로 작성해.
  - 질문의 종결 표현은 반드시 "~요?" 형태로 끝내. // 추가: "~인가요?", "~있나요?", "~괜찮을까요?" 등 해요체 사용
  - 사용자의 이전 답변에 따라 질문의 초점이 달라져야 해.
  - 모든 사용자에게 똑같이 사용할 수 있는 뻔한 질문보다 현재 사용자에게 필요한 질문을 우선해. // 추가: 적응형 질문 생성 강조
  - 단, 억지로 이전 답변을 언급해서 개인화한 것처럼 보이게 하지 마.
  - "결정적인 이유", "구매를 고려하는 이유"처럼 지나치게 딱딱한 표현은 가급적 피해야 해.
  - 인과관계가 없는 내용을 "~해서", "~라면", "~하려면" 등으로 억지로 이어 붙이지 마.
  - 사용자가 말하지 않은 상황을 사실인 것처럼 전제하지 마.

  [선택지 생성 원칙]

  - 방금 만든 질문에 직접 답할 수 있는 선택지 4개를 만들어줘.
  - 질문이 이전 답변에 따라 달라졌다면 선택지도 그 질문에 맞게 달라져야 해. // 추가: 질문만 개인화되고 선택지는 고정되는 문제 방지
  - 각 선택지는 15자 이내로 작성해.
  - 선택지끼리 의미가 최대한 겹치지 않게 해.
  - 사용자가 실제로 말한 내용은 참고해도 돼.
  - 사용자가 말하지 않은 상황은 임의로 만들어내지 마.
  - 상품명이나 제공된 정보에 없는 특징은 만들어내지 마.

  할인 여부가 제공된 상품 정보에서 명확하게 확인되는 경우에만
  "${AXES[2]}" 축의 선택지 중 하나로 "할인 중이라서"를 사용할 수 있어. // 변경: 할인 중이라고 모델이 임의로 판단하지 못하도록 제한

  JSON 형식으로만 반환:
  {
    "question": "질문 문장",
    "options": ["선택지1", "선택지2", "선택지3", "선택지4"]
  }
`)
}

export async function generateJudgment(productInfo, category, allQAs) {
  const history = allQAs
    .map((qa, i) => `Q${i + 1}(${qa.axis}): ${qa.question} → 답변: ${qa.answer}`)
    .join('\n')

  return generate(`
  상품명: ${productInfo.name}
  가격: ${productInfo.price?.toLocaleString()}원
  카테고리: ${category}

  사용자의 질문과 답변:
  ${history}

  지금까지의 답변을 바탕으로 각 답변을
  "좋음", "주의", "걸림" 중 하나로 판단하고 최종 판정을 내려줘.

  [판단 원칙]

  각 답변을 문장 자체만 보고 판단하지 말고,
  질문의 의미와 사용자의 답변을 함께 보고 판단해. // 추가: 동일한 답변 문자열이라도 질문 맥락에 따라 다르게 판단하도록 설정

  또한 사용자가 직접 말하지 않은 상황이나 정보를 추측해서 판정하지 마. // 추가: 최종 판정에서 임의 추론 방지

  [축별 판단 기준]

  "${AXES[0]}"
  - 비슷한 제품이 없거나 기존 제품을 대체할 필요가 명확하면 "좋음"
  - 어느 정도 비슷한 제품이 있지만 추가 구매 이유도 어느 정도 있으면 "주의"
  - 이미 충분히 비슷한 제품을 가지고 있고 추가 필요성이 낮으면 "걸림"

  "${AXES[1]}"
  - 실제로 자주 사용할 가능성이 높으면 "좋음"
  - 사용 빈도나 활용도가 애매하면 "주의"
  - 거의 사용하지 않을 가능성이 높으면 "걸림"

  "${AXES[2]}"
  - 지금 구매해야 할 구체적이고 합리적인 이유가 있으면 "좋음"
  - 이유가 있긴 하지만 꼭 지금일 필요는 없어 보이면 "주의"
  - 특별한 이유 없이 순간적으로 사고 싶은 것에 가까우면 "걸림"

  "${AXES[3]}"
  - 가격이 충분히 감당 가능하고 부담이 낮으면 "좋음"
  - 조금 부담되지만 감당할 수 있는 수준이면 "주의"
  - 구매가 현재 예산에 명확한 부담이 된다면 "걸림" // 변경: 축별로 판정 기준을 따로 정의해 모델의 일관성 강화

  [최종 판정 규칙]

  아래 규칙은 반드시 그대로 적용해.

  1. "걸림"이 2개 이상이면 → "추천하지 않아요"
  2. 그 외에 "걸림"이 정확히 1개이면 → "조금 더 생각해봐요"
  3. 그 외에 "주의"가 2개 이상이면 → "조금 더 생각해봐요"
  4. 그 외에는 → "구매해도 좋아요"

  판정 이유는 사용자가 실제로 답한 내용 중 핵심적인 근거를 사용해 한두 문장으로 작성해.
  답변에 없는 사실을 추가하지 마. // 추가: 결과 설명에서도 환각 방지

  JSON 형식으로만 반환:
  {
    "verdict": "구매해도 좋아요" | "조금 더 생각해봐요" | "추천하지 않아요",
    "signals": [
      {
        "axis": "축 이름",
        "answer": "사용자 답변",
        "signal": "좋음" | "주의" | "걸림"
      }
    ],
    "reason": "판정 이유 한두 문장"
  }
`)
}
